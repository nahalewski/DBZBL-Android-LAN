#!/usr/bin/env python3
"""Rebuild the component-wise BC2/BC3 texture-load shaders (glslang + SPIR-V tools)."""
from pathlib import Path
import struct
import subprocess

ROOT = Path(__file__).resolve().parents[1]
SHADERS = ROOT / "thirdparty/rexglue-sdk/src/graphics/shaders"

def main():
    output = ROOT / "out/bc-shader-build"
    output.mkdir(parents=True, exist_ok=True)
    for name in ("texture_load_dxt3_rgba8", "texture_load_dxt5_rgba8"):
        binary = output / (name + ".spv")
        subprocess.run(["glslangValidator", "-V", "--target-env", "vulkan1.0",
                        str(SHADERS / "glsl" / (name + ".comp")), "-o", str(binary)], check=True)
        subprocess.run(["spirv-val", "--target-env", "vulkan1.0", str(binary)], check=True)
        data = binary.read_bytes()
        words = struct.unpack("<" + "I" * (len(data) // 4), data)
        text = "// Generated by scripts/build_vulkan_bc_shaders.py from glsl/" + name + ".comp\n"
        text += "const uint32_t " + name + "_cs[] = {\n"
        for offset in range(0, len(words), 8):
            text += "    " + ", ".join(f"0x{value:08X}" for value in words[offset:offset+8]) + ",\n"
        text += "};\n"
        (SHADERS / "vulkan_spirv" / (name + "_cs.h")).write_text(text)

if __name__ == "__main__":
    main()
